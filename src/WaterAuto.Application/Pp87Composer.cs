using System.Globalization;
using WaterAuto.Calc.Hydraulics;
using WaterAuto.Core;
using WaterAuto.Reports;

namespace WaterAuto.Application;

/// <summary>Данные проекта для раздела 9 по п. 26 Положения (ПП РФ № 87): то, что программа рассчитала, и тома, которые выпущены.</summary>
public sealed record Pp87Inputs(
    NoteTitle Title,
    string ObjectName,
    IReadOnlyList<Room> ProtectedRooms,
    int Sprinklers,
    DesignResult Design,
    string GroupsText,
    bool AirFilled,
    IReadOnlyList<CurtainResult> Curtains,
    int Hydrants,
    string? PumpText,
    IReadOnlyList<string> OtherVolumes,
    IReadOnlyList<string> Schemes);

/// <summary>
/// Раздел 9 «Мероприятия по обеспечению пожарной безопасности» в части систем противопожарной защиты по составу п. 26 Положения
/// о составе разделов проектной документации (ПП РФ от 16.02.2008 № 87, ред. от 21.10.2025). Программа заполняет подпункты,
/// которые следуют из её расчётов (з, и, к, п); остальные — проектировщик, они перечислены с пометкой.
/// </summary>
public static class Pp87Composer
{
    private static readonly CultureInfo Ru = CultureInfo.GetCultureInfo("ru-RU");

    private static string F(double v, string fmt = "0.##") => v.ToString(fmt, Ru);

    public static NoteDocument Compose(Pp87Inputs i)
    {
        ArgumentNullException.ThrowIfNull(i);
        var d = i.Design;
        static NoteSection Designer(string letter, string heading) =>
            new(letter, heading, [new NotePending("Заполняется проектировщиком по архитектурным, конструктивным и технологическим решениям объекта — в расчёт программы не входит.")]);
        var aupt = new List<string>
        {
            $"автоматическая установка пожаротушения — спринклерная {(i.AirFilled ? "воздухозаполненная" : "водозаполненная")} водяная по СП 485.1311500.2020; {i.GroupsText};",
            string.Create(Ru, $"оросителей — {i.Sprinklers} шт.; расчётный расход — {d.DesignFlow.LitersPerSecond:0.00} л/с, расход насоса — {d.PumpFlow.LitersPerSecond:0.00} л/с, требуемый напор — {d.PumpHead.Meters:0.0} м, продолжительность подачи — {d.Duration:0} мин, запас воды — {d.WaterVolume:0.0} м³;"),
        };
        if (i.PumpText is { Length: > 0 } pump)
        {
            aupt.Add(pump + ";");
        }

        aupt.AddRange(i.Curtains.Where(c => c.PerRow > 0).Select(c => string.Create(Ru,
            $"водяная завеса «{c.Input.Name}» (ширина {c.Input.WidthM:0.##} м): {c.Rows} нитк. по {c.PerRow} дренчерных оросителей, расход {c.TotalFlow.LitersPerSecond:0.00} л/с (пп. 6.3.10, 6.3.11 СП 485);")));
        aupt.Add(i.Hydrants > 0
            ? string.Create(Ru, $"внутренний противопожарный водопровод совмещён с АУП: пожарных кранов — {i.Hydrants} шт., расход учтён в расчёте насоса (Б.1.3.16 СП 485);")
            : "внутренний противопожарный водопровод в расчёт АУП не включён — по отдельному решению;");
        aupt.AddRange(i.OtherVolumes.Select(v => v + ";"));
        aupt.Add("противодымная защита — по разделу «Отопление, вентиляция и кондиционирование воздуха»; сигналы управления — от системы пожарной сигнализации.");

        var sections = new List<NoteSection>
        {
            new("", "Общие положения", [
                new NoteParagraph($"Раздел составлен для объекта «{i.ObjectName}» по составу п. 26 Положения о составе разделов проектной документации и требованиях к их содержанию (постановление Правительства РФ от 16.02.2008 № 87). Подпункты з), и), к), п) заполнены по результатам расчётов систем противопожарной защиты; остальные подпункты заполняет проектировщик."),
            ]),
            Designer("а)", "Описание системы обеспечения пожарной безопасности объекта"),
            Designer("б)", "Обоснование противопожарных расстояний"),
            Designer("в)", "Наружное противопожарное водоснабжение, проезды и подъезды для пожарной техники"),
            Designer("г)", "Конструктивные и объёмно-планировочные решения, степень огнестойкости и класс конструктивной пожарной опасности"),
            Designer("д)", "Проектные решения по обеспечению безопасности людей при пожаре"),
            Designer("е)", "Мероприятия по обеспечению безопасности подразделений пожарной охраны"),
            Designer("ж)", "Категории зданий, помещений и наружных установок по взрывопожарной и пожарной опасности"),
            new("з)", "Перечень помещений, подлежащих защите автоматическими установками пожаротушения и пожарной сигнализацией", [
                new NoteTable("Помещения, защищаемые АУП", ["№", "Помещение", "Площадь, м²"],
                    [.. i.ProtectedRooms.Select((r, k) => (IReadOnlyList<string>)[(k + 1).ToString(Ru), r.Name, F(r.Contour.AreaMm2 / 1e6, "0.0")])]),
                new NotePending("Необходимость защиты (перечень помещений по СП 486.1311500) определяет проектировщик; таблица — помещения, для которых в проекте выполнена АУП."),
            ]),
            new("и)", "Описание и обоснование технических систем противопожарной защиты", [new NoteList(aupt)]),
            new("к)", "Размещение, управление и взаимодействие систем противопожарной защиты", [
                new NoteList([
                    "узел управления АУП — в помещении насосной станции или ином помещении по п. 6.8.2 СП 485; запорные устройства с контролем положения;",
                    "пуск пожарных насосов — автоматически по сигналу узла управления, дистанционно и по месту; при пожаре жокей-насос отключается, при отказе рабочего насоса включается резервный;",
                    "сигналы о срабатывании узла управления, пуске насосов, положении запорных устройств и неисправности передаются в систему пожарной сигнализации;",
                    "по сигналу «Пожар» система пожарной сигнализации включает СОУЭ, отключает общеобменную вентиляцию и включает противодымную защиту (СП 484.1311500, разд. 7).",
                ]),
                new NotePending("Алгоритм работы и перечень сигналов — в пояснительной записке АУПТ (раздел «Принцип действия») и в томе АПС (таблица сигналов, взаимодействие)."),
            ]),
            Designer("л)", "Организационно-технические мероприятия по обеспечению пожарной безопасности"),
            Designer("м)", "Расчёт пожарных рисков (при необходимости)"),
            Designer("н)", "Ситуационный план: проезды пожарной техники, пожарные водоёмы и гидранты, насосные станции"),
            Designer("о)", "Схемы эвакуации людей и материальных средств"),
            new("п)", "Структурные схемы технических систем противопожарной защиты", [
                new NoteList(i.Schemes.Count > 0 ? [.. i.Schemes] : ["схемы выпускаются в томах соответствующих систем"]),
            ]),
        };
        return new NoteDocument(i.Title with { Title = "Раздел 9. Мероприятия по обеспечению пожарной безопасности" }, sections, []);
    }
}
